"""End-to-end pipeline: prepare data -> train model -> run benchmark.

Usage:
    python scripts/run_benchmark.py                # train + full benchmark (uses LLM)
    python scripts/run_benchmark.py --no-llm        # skip LLM queries (proxy ASR)
    python scripts/run_benchmark.py --prepare-only  # only build training data
    python scripts/run_benchmark.py --train-only    # only train the model
    python scripts/run_benchmark.py --sample 30     # limit benchmark rows
    python scripts/run_benchmark.py --pdf-dir data/pdf_payloads --no-train  # benchmark sobre PDFs
    python scripts/run_benchmark.py --audio-dir data/audio_payloads --no-train --no-llm  # sobre audios
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from promption.benchmark.runner import BenchmarkRunner, RunnerOptions  # noqa: E402
from promption.filter.ensemble_filter import build_default  # noqa: E402
from promption.training.artifacts import selected_backend, preserve_records
from promption.training import dataset as dataset_mod  # noqa: E402
from promption.utils.config import load_config  # noqa: E402
from promption.utils.logger import logger  # noqa: E402


def _load_pdf_dataset(pdf_dir: Path):
    """Build an evaluation DataFrame from a directory generated by generate_pdf_payloads.py."""
    import pandas as pd

    from promption.utils.pdf_extractor import extract_pdf_text

    meta = pdf_dir / "metadata.csv"
    if meta.exists():
        meta_df = pd.read_csv(meta, encoding="utf-8")
    else:
        meta_df = pd.DataFrame([{
            "file": p.name,
            "prompt": "",
            "label": 1 if p.name.lower().startswith("mal") else 0,
            "dataset": "PDF",
            "attack_type": "pdf",
            "source": p.name,
        } for p in sorted(pdf_dir.glob("*.pdf"))])

    rows = []
    for r in meta_df.itertuples(index=False):
        text = extract_pdf_text(pdf_dir / r.file)
        if not text:
            logger.warning("PDF sin texto extraíble (¿escaneado?): %s", r.file)
            continue
        rows.append({
            "prompt": text,
            "label": int(r.label),
            "dataset": str(getattr(r, "dataset", "PDF") or "PDF"),
            "attack_type": str(getattr(r, "attack_type", "pdf") or "pdf"),
            "source": str(getattr(r, "source", r.file) or r.file),
        })
    df = pd.DataFrame(rows).reset_index(drop=True)
    logger.info("Benchmark PDF: %d documentos con texto extraído.", len(df))
    return df


def _load_audio_dataset(audio_dir: Path):
    """Build an evaluation DataFrame from a directory generated by generate_audio_payloads.py."""
    import pandas as pd

    from promption.utils.audio_transcriber import transcribe

    meta = audio_dir / "metadata.csv"
    if meta.exists():
        meta_df = pd.read_csv(meta, encoding="utf-8")
    else:
        meta_df = pd.DataFrame([{
            "file": p.name,
            "prompt": "",
            "label": 1 if p.name.lower().startswith("mal") else 0,
            "dataset": "AUDIO",
            "attack_type": "audio",
            "source": p.name,
        } for p in sorted(audio_dir.glob("*.*")) if p.suffix.lower() in (".wav", ".mp3", ".m4a", ".ogg", ".flac")])

    logger.info("Transcribiendo %d audios con modelo '%s' (1ª vez descarga el modelo)…",
                len(meta_df), load_config().get("stt", {}).get("model", "tiny"))
    lang = load_config().get("stt", {}).get("language")
    rows = []
    for r in meta_df.itertuples(index=False):
        text = transcribe(audio_dir / r.file, language=lang or None)
        if not text:
            logger.warning("Audio sin transcripción: %s", r.file)
            continue
        rows.append({
            "prompt": text,
            "label": int(r.label),
            "dataset": str(getattr(r, "dataset", "AUDIO") or "AUDIO"),
            "attack_type": str(getattr(r, "attack_type", "audio") or "audio"),
            "source": str(getattr(r, "source", r.file) or r.file),
        })
    df = pd.DataFrame(rows).reset_index(drop=True)
    logger.info("Benchmark audio: %d archivos transcritos.", len(df))
    return df


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--no-llm", action="store_true", help="Disable Ollama queries")
    parser.add_argument("--prepare-only", action="store_true")
    parser.add_argument("--train-only", action="store_true")
    parser.add_argument("--sample", type=int, default=None)
    parser.add_argument("--no-train", action="store_true", help="Skip model training if a model file exists")
    parser.add_argument("--pdf-dir", type=Path, default=None,
                        help="Benchmark personalizado sobre los PDF de este directorio (metadatos en metadata.csv)")
    parser.add_argument("--audio-dir", type=Path, default=None,
                        help="Benchmark personalizado sobre audios transcritos (metadatos en metadata.csv)")
    args = parser.parse_args()

    pdf_df = None
    if args.pdf_dir and args.audio_dir:
        raise SystemExit("Elegir solo uno: --pdf-dir o --audio-dir, no ambos.")
    if args.pdf_dir:
        pdf_df = _load_pdf_dataset(args.pdf_dir)
    elif args.audio_dir:
        pdf_df = _load_audio_dataset(args.audio_dir)
    else:
        dataset_mod.prepare_training_data()
        if args.prepare_only:
            logger.info("Dataset built. Run `python scripts/run_benchmark.py --train-only` to train the selected backend.")
            return

    backend, model_path = selected_backend()
    backup = preserve_records()
    logger.info("Previous models and results preserved in %s", backup)
    if args.train_only or not model_path.exists() or not args.no_train:
        if backend == "tfidf_logistic_regression":
            from promption.training.train_lightweight import train
            train(out_path=model_path, preserve=False)
        else:
            from promption.training.train import main as train
            train(out_path=str(model_path), preserve=False)

    if args.train_only:
        return

    ensemble = build_default()
    ensemble.ml._ensure_loaded()
    runner = BenchmarkRunner(
        filter=ensemble,
        opts=RunnerOptions(data=pdf_df, sample_size=args.sample, use_llm=not args.no_llm),
    )
    df, metrics = runner.run()
    asr_no = f"{metrics['asr_without_filter']:.3f}" if metrics.get("asr_without_filter") is not None else "N/A"
    asr_with = f"{metrics['asr_with_filter']:.3f}" if metrics.get("asr_with_filter") is not None else "N/A"
    asr_red = f"{metrics['asr_reduction'] * 100:.1f}%" if metrics.get("asr_reduction") is not None else "N/A"
    logger.info("ASR sin filtro: %s | ASR con filtro: %s | Reducción: %s", asr_no, asr_with, asr_red)
    logger.info("Precisión: %.3f | Recall: %.3f | F1: %.3f",
                metrics["precision"], metrics["recall"], metrics["f1"])


if __name__ == "__main__":
    main()
